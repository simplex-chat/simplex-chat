/* Caller-contract unit only. These deliberately scripted Win32/RTS APIs do
 * not qualify OS path handling, Wine, the target ABI, or the full RTS. */
typedef unsigned long DWORD;
typedef void *HsPtr;
typedef wchar_t pathchar;
#define PATH_FMT "ls"
#define ERROR_INVALID_PARAMETER 87UL
#define ERROR_INSUFFICIENT_BUFFER 122UL
#define ERROR_PATH_NOT_FOUND 3UL
#define ERROR_ACCESS_DENIED 5UL

static const DWORD capacity = 32768;
static const wchar_t short_path[] = L"C:\\fixture";
static char cookie;
static struct {
    const wchar_t *input;
    const wchar_t *resolved;
    bool converted;
    bool add_fails;
    DWORD resolve_result;
    DWORD last_error;
    unsigned resolve_calls;
    unsigned convert_calls;
    unsigned add_calls;
    unsigned diagnostics;
    unsigned allocations;
    unsigned releases;
    void *absolute_allocation;
    void *converted_allocation;
} state;

#define CHECK(condition) do { \
    if (!(condition)) { \
        fprintf(stderr, "FAIL line %d: %s\n", __LINE__, #condition); \
        exit(1); \
    } \
} while (0)

static void SetLastError(DWORD error) { state.last_error = error; }
static DWORD GetLastError(void) { return state.last_error; }

static void *stgMallocBytes(size_t size, char *message) {
    (void)message;
    CHECK(state.absolute_allocation == NULL);
    void *result = malloc(size);
    CHECK(result != NULL);
    state.absolute_allocation = result;
    state.allocations++;
    return result;
}

static void stgFree(void *pointer) {
    CHECK(pointer != NULL);
    CHECK(pointer == state.absolute_allocation
          || pointer == state.converted_allocation);
    if (pointer == state.absolute_allocation) {
        state.absolute_allocation = NULL;
    } else {
        state.converted_allocation = NULL;
    }
    state.releases++;
    free(pointer);
    SetLastError(0xdeadUL); /* Cleanup must not overwrite the API error. */
}

static void sysErrorBelch(const char *format, ...) {
    (void)format;
    state.diagnostics++;
    SetLastError(0xbeefUL); /* Nor may a diagnostic overwrite it. */
}

static DWORD GetFullPathNameW(const wchar_t *input, DWORD size,
                              wchar_t *output, wchar_t **part) {
    state.resolve_calls++;
    CHECK(state.resolve_calls == 1);
    CHECK(input == state.input && size == capacity && part == NULL);
    CHECK(output == state.absolute_allocation);
    if (state.resolve_result == 0) {
        SetLastError(ERROR_PATH_NOT_FOUND);
    } else if (state.resolve_result < size) {
        CHECK(wcslen(state.resolved) == state.resolve_result);
        wmemcpy(output, state.resolved, state.resolve_result + 1);
    }
    return state.resolve_result;
}

static wchar_t *__rts_create_device_name(const wchar_t *input) {
    state.convert_calls++;
    CHECK(input == state.absolute_allocation);
    CHECK(wcscmp(input, state.resolved) == 0);
    if (!state.converted) {
        SetLastError(0x1234UL);
        return NULL;
    }
    const wchar_t converted[] = L"\\\\?\\C:\\fixture";
    wchar_t *result = malloc(sizeof(converted));
    CHECK(result != NULL);
    wmemcpy(result, converted, sizeof(converted) / sizeof(converted[0]));
    state.converted_allocation = result;
    state.allocations++;
    return result;
}

static HsPtr AddDllDirectory(const wchar_t *path) {
    state.add_calls++;
    CHECK(path != NULL);
    CHECK(path == (state.converted ? state.converted_allocation
                                  : state.absolute_allocation));
    SetLastError(state.add_fails ? ERROR_ACCESS_DENIED : 0x55UL);
    return state.add_fails ? NULL : &cookie;
}

