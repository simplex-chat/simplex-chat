#include "candidate-body.inc"

static void reset(const wchar_t *input, const wchar_t *resolved,
                  DWORD result, bool converted, bool add_fails) {
    CHECK(state.absolute_allocation == NULL);
    CHECK(state.converted_allocation == NULL);
    memset(&state, 0, sizeof(state));
    state.input = input;
    state.resolved = resolved;
    state.resolve_result = result;
    state.converted = converted;
    state.add_fails = add_fails;
}

static void invalid_input(const wchar_t *input) {
    reset(input, NULL, 0, false, false);
    CHECK(addLibrarySearchPath_PEi386((pathchar *)input) == NULL);
    CHECK(GetLastError() == ERROR_INVALID_PARAMETER);
    CHECK(state.resolve_calls == 0 && state.convert_calls == 0
          && state.add_calls == 0 && state.allocations == 0);
}

static void resolution_failure(DWORD result, DWORD error) {
    reset(L"relative", NULL, result, false, false);
    CHECK(addLibrarySearchPath_PEi386((pathchar *)state.input) == NULL);
    CHECK(GetLastError() == error);
    CHECK(state.resolve_calls == 1 && state.convert_calls == 0
          && state.add_calls == 0 && state.allocations == state.releases);
}

static void resolved_path(const wchar_t *input, const wchar_t *resolved,
                          bool converted, bool add_fails) {
    reset(input, resolved, (DWORD)wcslen(resolved), converted, add_fails);
    HsPtr result = addLibrarySearchPath_PEi386((pathchar *)input);
    CHECK(result == (add_fails ? NULL : &cookie));
    CHECK(GetLastError() == (add_fails ? ERROR_ACCESS_DENIED : 0x55UL));
    CHECK(state.resolve_calls == 1 && state.convert_calls == 1
          && state.add_calls == 1);
    CHECK(state.allocations == state.releases);
    CHECK(state.absolute_allocation == NULL && state.converted_allocation == NULL);
}

int main(void) {
    invalid_input(NULL);
    invalid_input(L"");
    resolution_failure(0, ERROR_PATH_NOT_FOUND);
    resolution_failure(capacity, ERROR_INSUFFICIENT_BUFFER);
    resolution_failure(capacity + 1, ERROR_INSUFFICIENT_BUFFER);
    resolved_path(L"relative", short_path, false, false);
    resolved_path(L"relative", short_path, true, false);
    resolved_path(L"relative", short_path, false, true);
    resolved_path(L"relative", short_path, true, true);
    resolved_path(L"\\\\?\\C:\\fixture", L"\\\\?\\C:\\fixture", false, false);
    resolved_path(L"\\\\server\\share", L"\\\\server\\share", false, false);
    wchar_t *long_path = malloc(capacity * sizeof(wchar_t));
    CHECK(long_path != NULL);
    wmemset(long_path, L'a', capacity - 1);
    long_path[0] = L'C';
    long_path[1] = L':';
    long_path[2] = L'\\';
    long_path[capacity - 1] = L'\0';
    resolved_path(L"relative", long_path, false, false);
    free(long_path);
    puts("PASS 12 mocked caller boundary controls; no Windows/Wine runtime claim");
    return 0;
}
